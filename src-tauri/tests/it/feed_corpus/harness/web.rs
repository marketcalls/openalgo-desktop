//! The case's expected frames against the web's output for the same raw
//! frames: `web.json`, written by `scripts/feed_corpus/web_expected.py`,
//! which runs the web adapter's own decoding and normalising methods on
//! the case's pushes (README, "The web's output").
//!
//! For every frame a client receives after a delivery point (a push, or
//! any step that made the web adapter publish), the frame the web's own
//! server sends that client is found (`deliveries.rs`: each web frame
//! consumed once per held mode, in order, by instrument and mode; an order
//! update by its id), and the two `data` objects (whole frames for order
//! updates) are compared key by key. Every web frame that answers a held
//! mode and that no receive consumes must be declared by a `silence` step
//! naming it (`missing-frame`), before the next delivery point.
//! Every key on which they differ must be one of the case's deviations,
//! and every deviation must be such a difference, so a deviation cannot
//! outlive its cause. A deviation also says which differences it covers
//! (`allows`, generated by `scripts/feed_corpus/predicates.py`): a named
//! class with no freedom in it, or the exact pair seen, so a value outside
//! what was seen fails, and something allowed that no frame shows fails too.
//! The web's reply to each send (`replies`: the web server's own answer from
//! the adapter's own `subscribe`, where it could run) is compared the same
//! way with the case's expected reply, under keys `reply.<key>`.
//! A `random-values` key is compared by presence and
//! JSON type only, and the web's publish must keep the case's invariants
//! too. The live run has already shown the expected frames are the
//! desktop's.

use super::case::{
    bad, corpus_root, read_json, Action, Case, Step, WebFrame, WebPair, MISSING_FRAME,
};
use super::deliveries::{self, Consumer, Paired};
use super::invariants;
use super::json_text;
use serde_json::{Map, Value};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

/// The deviation key for a frame the web does not send at all.
const NO_WEB_FRAME: &str = "frame";
/// A side of a difference that has no value, as `allows` writes it.
const ABSENT: &str = "<absent>";
/// The deviation key for the web's fan-out to a lower-mode holder that
/// answers none of its held modes.
const FAN_OUT: &str = "fan-out";
/// The steps the web replay does not model: `web.json` lists them
/// (`uncompared`), and the release gate counts them.
const UNMODELLED_STEPS: &[&str] = &["refuse_upgrades", "disconnect"];

pub(crate) fn check(case: &Case) {
    let path = case.dir.join("web.json");
    let at = format!("{} web.json", case.id);
    if !path.exists() {
        if case.by_hand {
            return;
        }
        bad(
            &at,
            "missing: every case is compared with the web unless its provenance is \"by-hand\"",
        );
    }
    let web = read_json(&path);
    let digest = hex::encode(Sha256::digest(&case.inputs));
    if web["inputs_sha256"] != digest.as_str() {
        bad(
            &at,
            "computed from another script or other frames: run scripts/feed_corpus/web_expected.py again",
        );
    }
    let pin = read_json(&corpus_root().join("web_oracle.json"));
    if web["web_sha"] != pin["web_sha"] {
        bad(
            &at,
            format!(
                "computed at web {} but the corpus is pinned to {}: run scripts/feed_corpus/web_expected.py at that commit",
                web["web_sha"], pin["web_sha"]
            ),
        );
    }
    if web["instruments"] != case.instruments_json {
        bad(&at, "computed with other instruments than case.json's");
    }
    let sha = web["web_sha"].as_str().unwrap_or_default();
    if sha.is_empty() || !(sha.starts_with(&case.web_sha) || case.web_sha.starts_with(sha)) {
        bad(
            &at,
            format!(
                "computed at web {}, but case.json's provenance says {}",
                sha, case.web_sha
            ),
        );
    }
    check_uncompared(&at, case, &web);
    let points = deliveries::points(&at, &web);
    let push_lines: BTreeSet<usize> = case
        .steps
        .iter()
        .filter(|s| matches!(s.action, Action::Push { .. } | Action::HttpServe(_)))
        .map(|s| s.line)
        .collect();
    let step_lines: BTreeSet<usize> = case.steps.iter().map(|s| s.line).collect();
    if !push_lines.iter().all(|l| points.contains_key(l))
        || !points.keys().all(|l| step_lines.contains(l))
    {
        bad(
            &at,
            "its delivery points are not the script's: run scripts/feed_corpus/web_expected.py again",
        );
    }

    let mut cmp = Comparison {
        case,
        diffs: BTreeMap::new(),
        unconsumed: Vec::new(),
    };
    check_replies(&at, case, &web, &mut cmp);
    let mut current: Option<Consumer> = None;
    for step in &case.steps {
        let at = format!("{} script.jsonl:{}", case.id, step.line);
        if let Some(point) = points.get(&step.line) {
            if let Some(c) = current.take() {
                cmp.close(&c);
            }
            current = Some(Consumer::new(step.line, point));
            continue;
        }
        let Some(c) = current.as_mut() else {
            continue;
        };
        match &step.action {
            Action::Receive { client, frame, web } => {
                let theirs = match (web, frame["type"].as_str()) {
                    (WebPair::Nothing, _) => None,
                    (WebPair::Mode(_), Some("order_update")) => c.order(client, &frame["orderid"]),
                    (WebPair::Mode(mode), _) => c.market(
                        client,
                        frame["symbol"].as_str().unwrap_or_default(),
                        frame["exchange"].as_str().unwrap_or_default(),
                        mode.map(u64::from)
                            .or_else(|| frame["mode"].as_u64())
                            .unwrap_or(0),
                    ),
                };
                match (theirs, web) {
                    (Some(theirs), _) => cmp.frames(&at, frame, theirs),
                    (None, WebPair::Nothing) => {
                        c.web_false(step.line, client, frame);
                        cmp.record(
                            NO_WEB_FRAME,
                            Seen::frame(
                                format!("{}: the web sends nothing for this frame", at),
                                absent(),
                                frame_identity(frame),
                            ),
                        );
                    }
                    (None, WebPair::Mode(_)) => bad(
                        &at,
                        format!(
                            "the web sends client {} nothing this frame could answer (delivery point at line {}): \
                             mark the step \"web\": false and add a deviation \"{}\"",
                            client, c.line, NO_WEB_FRAME
                        ),
                    ),
                }
            }
            Action::Silence {
                client,
                web: Some(w),
                ..
            } => {
                let Some(theirs) = c.web_only(client, &w.symbol, &w.exchange, u64::from(w.mode))
                else {
                    bad(
                        &at,
                        format!(
                            "the web sends client {} no {} {} frame at mode {} after line {} either: drop \"web\"",
                            client, w.exchange, w.symbol, w.mode, c.line
                        ),
                    );
                };
                cmp.web_only(&at, w, theirs.publication);
            }
            _ => {}
        }
    }
    if let Some(c) = current.take() {
        cmp.close(&c);
    }
    if !cmp.unconsumed.is_empty() {
        bad(
            &at,
            format!(
                "web frames the case neither receives nor declares (a silence step naming each, deviation \"{}\"):\n  {}",
                MISSING_FRAME,
                cmp.unconsumed.join("\n  ")
            ),
        );
    }
    report(&at, case, &cmp.diffs);
}

/// Each send's expected reply against the web's. A send whose adapter call
/// the web's method could not answer has no web reply to compare.
fn check_replies(at: &str, case: &Case, web: &Value, cmp: &mut Comparison) {
    let replies = web["replies"].as_array().map_or(&[][..], Vec::as_slice);
    let sends: Vec<&Step> = case
        .steps
        .iter()
        .filter(|s| matches!(s.action, Action::Send { .. }))
        .collect();
    let lines: Vec<u64> = replies.iter().filter_map(|r| r["line"].as_u64()).collect();
    let script: Vec<u64> = sends.iter().map(|s| s.line as u64).collect();
    if lines != script {
        bad(
            at,
            "its replies are not the script's sends: run scripts/feed_corpus/web_expected.py again",
        );
    }
    for (step, web_reply) in sends.iter().zip(replies) {
        if web_reply["from_adapter"] != true {
            continue;
        }
        let at = format!("{} script.jsonl:{}", case.id, step.line);
        let frames = web_reply["frames"]
            .as_array()
            .map_or(&[][..], Vec::as_slice);
        let [theirs] = frames else {
            bad(
                &at,
                format!("the web answers this send with {} frames", frames.len()),
            );
        };
        match &step.action {
            Action::Send { reply: Some(mine), .. } => cmp.replies(&at, mine, theirs),
            _ => bad(
                &at,
                format!(
                    "the web answers {}: give the step its \"reply\" (scripts/feed_corpus/predicates.py --pin-replies)",
                    theirs
                ),
            ),
        }
    }
}

/// `web.json` names exactly the steps the replay does not model, so none
/// is taken for compared (`UNMODELLED_STEPS`, and a deep feed not made).
fn check_uncompared(at: &str, case: &Case, web: &Value) {
    let script = std::fs::read_to_string(case.dir.join("script.jsonl"))
        .unwrap_or_else(|e| bad(at, format!("script.jsonl: {}", e)));
    let mut want: Vec<Value> = Vec::new();
    if case.deep_feed_not_made {
        want.push(serde_json::json!({"line": 0, "step": "deep_feed_not_made"}));
    }
    for (n, line) in script.lines().enumerate() {
        let step = json_text::parse(line).ok();
        let kind = step.as_ref().and_then(|s| s["step"].as_str());
        if let Some(kind) = kind.filter(|k| UNMODELLED_STEPS.contains(k)) {
            want.push(serde_json::json!({"line": n + 1, "step": kind}));
        }
    }
    if web["uncompared"] != Value::Array(want) {
        bad(
            at,
            "its uncompared steps are not the script's: run scripts/feed_corpus/web_expected.py again",
        );
    }
}

/// A value's shape: its JSON type at every level, with the keys of every
/// object and the length of every list; a `<random:..>` placeholder is
/// the type it names.
fn shape(v: &Value) -> Value {
    match v {
        Value::Object(o) => Value::Object(o.iter().map(|(k, v)| (k.clone(), shape(v))).collect()),
        Value::Array(a) => Value::Array(a.iter().map(shape).collect()),
        Value::String(s) => match s.strip_prefix("<random:").and_then(|t| t.strip_suffix('>')) {
            Some(t) => Value::String(t.into()),
            None => Value::String("string".into()),
        },
        Value::Number(n) if n.is_f64() => Value::String("float".into()),
        Value::Number(_) => Value::String("int".into()),
        Value::Bool(_) => Value::String("bool".into()),
        Value::Null => Value::Null,
    }
}

/// One difference from the web, as a deviation's `allows` reads it.
#[derive(Debug, Clone)]
struct Seen {
    at: String,
    web: Value,
    desktop: Value,
    /// The web frame's `data`, which a derived value is checked against.
    web_data: Value,
}

impl Seen {
    /// A difference in a whole frame or its envelope, with no `data`.
    fn frame(at: String, web: Value, desktop: Value) -> Seen {
        Seen {
            at,
            web,
            desktop,
            web_data: Value::Null,
        }
    }
}

/// A list of objects, item by item.
fn item_objects(v: &Value) -> Option<Vec<&Map<String, Value>>> {
    v.as_array()?.iter().map(Value::as_object).collect()
}

fn absent() -> Value {
    Value::String(ABSENT.into())
}

fn side(v: Option<&Value>) -> Value {
    v.cloned().unwrap_or_else(absent)
}

/// A frame-level difference's value: which instrument and mode it is.
fn frame_identity(frame: &Value) -> Value {
    serde_json::json!({
        "symbol": frame["symbol"],
        "exchange": frame["exchange"],
        "mode": frame["mode"],
    })
}

/// A change the web computed from an `ltp` of 0 in the same frame.
fn from_zero_ltp(key: &str, seen: &Seen) -> bool {
    let data = &seen.web_data;
    let (Some(web), Some(ltp), Some(close)) = (
        seen.web.as_f64(),
        data["ltp"].as_f64(),
        data["close"].as_f64(),
    ) else {
        return false;
    };
    ltp == 0.0 && ((key == "change" && web == -close) || (key == "change_percent" && web == -100.0))
}

/// Is this difference one the named class covers? (`ALLOW_CLASSES`)
fn class_matches(class: &str, key: &str, seen: &Seen) -> bool {
    let left_out = seen.desktop.as_str() == Some(ABSENT);
    match class {
        "same-shape" => true,
        "zero-left-out" => left_out && seen.web.as_f64() == Some(0.0),
        "null-left-out" => left_out && seen.web.is_null(),
        "change-from-zero-ltp" => left_out && from_zero_ltp(key, seen),
        _ => false,
    }
}

/// Is this difference what one item of an `allows` covers?
fn allow_matches(allow: &Value, key: &str, seen: &Seen) -> bool {
    match allow {
        Value::String(class) => class_matches(class, key, seen),
        Value::Array(pair) => pair.len() == 2 && pair[0] == seen.web && pair[1] == seen.desktop,
        _ => false,
    }
}

/// The differences found, by deviation key.
struct Comparison<'a> {
    case: &'a Case,
    diffs: BTreeMap<String, Vec<Seen>>,
    /// What the delivery points left unanswered, for every point at once.
    unconsumed: Vec<String>,
}

impl Comparison<'_> {
    fn record(&mut self, key: &str, seen: Seen) {
        self.diffs.entry(key.to_string()).or_default().push(seen);
    }

    /// The end of a delivery point: what it left unanswered, and the web's
    /// fan-out, which a case declares.
    fn close(&mut self, point: &Consumer) {
        self.unconsumed.extend(point.unconsumed());
        self.unconsumed.extend(point.not_silent());
        for fan in point.fan_out() {
            self.record(FAN_OUT, Seen::frame(fan.text, fan.identity, absent()));
        }
    }

    /// The desktop's frame against the web's output: the envelope and the
    /// `data` of a market frame, the whole of an order update.
    fn frames(&mut self, at: &str, mine: &Value, theirs: Paired) {
        let publication = theirs.publication;
        if mine["type"] == "order_update" {
            self.differences(at, mine, &publication["frame"]);
        } else {
            self.keeps_invariants(at, publication);
            self.envelope(at, mine, theirs);
            self.differences(at, &mine["data"], &publication["data"]);
        }
    }

    /// The frame's envelope beside its `data`: the mode the web tags the
    /// client's frame with and the broker it names.
    fn envelope(&mut self, at: &str, mine: &Value, theirs: Paired) {
        let d = theirs.delivery;
        if mine["mode"].as_u64() != d.tag {
            self.record(
                "envelope.mode",
                Seen::frame(
                    at.to_string(),
                    serde_json::json!(d.tag),
                    mine["mode"].clone(),
                ),
            );
        }
        if mine["broker"].as_str() != d.broker.as_deref() {
            self.record(
                "envelope.broker",
                Seen::frame(
                    at.to_string(),
                    serde_json::json!(d.broker),
                    mine["broker"].clone(),
                ),
            );
        }
    }

    /// A web frame the desktop does not send.
    fn web_only(&mut self, at: &str, w: &WebFrame, theirs: &Value) {
        self.keeps_invariants(at, theirs);
        self.record(
            &w.deviation,
            Seen {
                at: format!(
                    "{}: the web sends {} {} at mode {} ({}), the desktop nothing",
                    at, w.exchange, w.symbol, w.mode, theirs["data"]
                ),
                web: serde_json::json!({"symbol": w.symbol, "exchange": w.exchange, "mode": w.mode}),
                desktop: absent(),
                web_data: theirs["data"].clone(),
            },
        );
    }

    /// An invariant the web's own publish breaks is not the web's
    /// behaviour, so it cannot stand for it.
    fn keeps_invariants(&self, at: &str, theirs: &Value) {
        let Some(publish) = theirs.as_object() else {
            return;
        };
        let mut applied = vec![0; self.case.invariants.len()];
        let broken = invariants::broken(&self.case.invariants, publish, &mut applied);
        if !broken.is_empty() {
            bad(
                at,
                format!(
                    "the web's publish breaks the case's invariants, so they are not the web's:\n  {}",
                    broken.join("\n  ")
                ),
            );
        }
    }

    /// The desktop's reply to a send against the web's: each key, and each
    /// key of the items of a list both have at one length.
    fn replies(&mut self, at: &str, mine: &Value, theirs: &Value) {
        let (Some(m), Some(t)) = (mine.as_object(), theirs.as_object()) else {
            bad(at, "the desktop's or the web's reply is not an object");
        };
        let keys: BTreeSet<&String> = m.keys().chain(t.keys()).collect();
        for k in keys {
            let (d, w) = (m.get(k), t.get(k));
            match (d.and_then(item_objects), w.and_then(item_objects)) {
                (Some(a), Some(b)) if a.len() == b.len() => {
                    for (x, y) in a.iter().zip(&b) {
                        self.reply_items(at, k, x, y);
                    }
                }
                _ if d != w => {
                    let seen = Seen::frame(at.to_string(), side(w), side(d));
                    self.record(&format!("reply.{}", k), seen);
                }
                _ => {}
            }
        }
    }

    fn reply_items(
        &mut self,
        at: &str,
        list: &str,
        mine: &Map<String, Value>,
        theirs: &Map<String, Value>,
    ) {
        let keys: BTreeSet<&String> = mine.keys().chain(theirs.keys()).collect();
        for k in keys {
            let (d, w) = (mine.get(k), theirs.get(k));
            if d != w {
                let seen = Seen::frame(at.to_string(), side(w), side(d));
                self.record(&format!("reply.{}.{}", list, k), seen);
            }
        }
    }

    fn seen(&self, at: &str, web: Option<&Value>, desktop: Option<&Value>, data: &Value) -> Seen {
        Seen {
            at: at.to_string(),
            web: side(web),
            desktop: side(desktop),
            web_data: data.clone(),
        }
    }

    fn differences(&mut self, at: &str, mine: &Value, theirs: &Value) {
        let (Some(m), Some(t)) = (mine.as_object(), theirs.as_object()) else {
            bad(at, "the desktop's or the web's frame is not an object");
        };
        let keys: BTreeSet<&String> = m.keys().chain(t.keys()).collect();
        for k in keys {
            let (d, w) = (m.get(k), t.get(k));
            if self.case.random.contains(k) {
                // Drawn at random on both sides: the same key, of the same
                // type, is all that can match.
                let same = d.zip(w).is_some_and(|(d, w)| shape(d) == shape(w));
                let key = if same {
                    k.clone()
                } else {
                    format!("{} (type)", k)
                };
                self.record(&key, self.seen(at, w, d, theirs));
            } else if d != w {
                self.record(k, self.seen(at, w, d, theirs));
            }
        }
    }
}

/// A difference, for a failure message.
fn described(key: &str, s: &Seen) -> String {
    format!(
        "\n  {} (web {}, desktop {}; {})",
        key, s.web, s.desktop, s.at
    )
}

/// Fail on a difference no deviation covers, a value outside what its
/// deviation allows, a deviation nothing shows, or an allowance nothing shows.
fn report(at: &str, case: &Case, diffs: &BTreeMap<String, Vec<Seen>>) {
    let mut used: Vec<Vec<bool>> = case
        .deviations
        .iter()
        .map(|d| vec![false; d.allows.len()])
        .collect();
    let (mut undeclared, mut outside) = (Vec::new(), Vec::new());
    for (key, list) in diffs {
        let entries: Vec<usize> = (0..case.deviations.len())
            .filter(|i| case.deviations[*i].key == *key)
            .collect();
        for seen in list {
            if entries.is_empty() {
                undeclared.push(described(key, seen));
                continue;
            }
            let hit = entries.iter().find_map(|i| {
                let allows = &case.deviations[*i].allows;
                let j = allows.iter().position(|a| allow_matches(a, key, seen))?;
                Some((*i, j))
            });
            match hit {
                Some((i, j)) => used[i][j] = true,
                None => outside.push(described(key, seen)),
            }
        }
    }
    let unused: Vec<&String> = case
        .deviations
        .iter()
        .zip(&used)
        .filter(|(_, u)| !u.iter().any(|x| *x))
        .map(|(d, _)| &d.key)
        .collect();
    let idle: Vec<String> = case
        .deviations
        .iter()
        .zip(&used)
        .filter(|(_, u)| u.iter().any(|x| *x))
        .flat_map(|(d, u)| {
            d.allows
                .iter()
                .zip(u)
                .filter(|(_, x)| !**x)
                .map(move |(a, _)| format!("\n  {}: {}", d.key, a))
        })
        .collect();
    if !outside.is_empty() {
        bad(
            at,
            format!(
                "values outside what their deviation allows (run scripts/feed_corpus/predicates.py only if the new value is right):{}",
                outside.join("")
            ),
        );
    }
    if !idle.is_empty() {
        bad(
            at,
            format!(
                "a deviation allows what no frame shows (run scripts/feed_corpus/predicates.py):{}",
                idle.join("")
            ),
        );
    }
    if !undeclared.is_empty() {
        bad(
            at,
            format!(
                "the desktop differs from the web where case.json declares no deviation:{}",
                undeclared.join("")
            ),
        );
    }
    if !unused.is_empty() {
        bad(
            at,
            format!(
                "deviations the frames no longer show (remove them): {:?}",
                unused
            ),
        );
    }
}

