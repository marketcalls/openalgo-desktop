"""Record the web Agent's settings contract as the desktop's fixture.

Reads the web's `services/agent/settings.py` (pure Python, no database is
touched) and writes `src-tauri/tests/fixtures/agent/settings.json`:

- `keys`: every `_SPEC` key in order with its kind, default (as
  `GET /agent/api/settings` renders defaults), bounds and choices;
- `voice_keys`, `websearch_keys` and the web search defaults;
- `strict`: what a write of each sample value stores, or the exact sentence
  that refuses it (`_parse(strict=True)` then `_serialise`);
- `lenient`: what a stored row reads as (`_parse(strict=False)` rendered as
  `get_all` renders it).

The desktop's settings tests (`agent::settings`) fail on any drift.

Usage, from the desktop repository root, with the web's interpreter:

    /path/to/openalgo/.venv/bin/python -I scripts/agent/capture_settings.py /path/to/openalgo

Regenerate only from the web; never edit the fixture by hand.
"""

from __future__ import annotations

import json
import sys
from decimal import Decimal
from pathlib import Path

OUT = Path("src-tauri/tests/fixtures/agent/settings.json")

# Sample values per kind: what a request body may carry.
SAMPLES = {
    "bool": [True, False, "true", "TRUE", " yes ", "on", "enabled", "0", "off", "disabled",
             1, 0, 1.0, "maybe", "", [], {"a": 1}],
    "int": [20, "20", " 7 ", "007", "1_000", -1, "-1", 0, 5.0, "5.5", "ten", "", True,
            "99999", [1], 3, 300, 301, 4, 30, 3600, 3601, 29],
    "money": [500000, "500000", "1.005", "1.004", "-0.01", "0", "1e3", "1E-7", "abc", "NaN",
              "Infinity", 12.5, True, "", " 250.50 ", "1_000.5", "+2"],
    "percent": ["5", "5.50", 100, "100.0", "100.01", "-1", "1e1", "0.000", "x", "-0", 99.999],
    "set": ["NSE,nfo", " nse , ,BSE ", "", '["mcx", "NCO"]', '["a"', '{"a": 1}', "[1, 2]",
            ["cnc", " mis "], [1, True, None], {"nse": 1}, 5, True, "ß"],
    "enum": ["low", "HIGH", " Medium ", "off", "max", "", 1, None],
    "text": ["Answer briefly.", "", "   ", 42, ["x"], True, "it's"],
}

# Stored rows as the store may hand them back.
STORED = {
    "bool": ["true", "false", "1", "garbage", ""],
    "int": ["20", "-5", "abc", "1_0", "999999999999"],
    "money": ["500000", "-3", "abc", "NaN", "12.345"],
    "percent": ["5", "150", "-2", "abc"],
    "set": ['["NSE", "BSE"]', "nse,bse", "[broken", "{}", ""],
    "enum": ["high", "bogus"],
    "text": ["hello", ""],
}


def _render(value):
    if isinstance(value, frozenset | set):
        return sorted(value)
    if isinstance(value, Decimal):
        return str(value)
    return value


def main(web_root: str) -> int:
    sys.path.insert(0, web_root)
    from services.agent import settings as s

    keys = []
    for key, field in s._SPEC.items():
        default = _render(field.default)
        if key == s.KEY_KILL_SWITCH_FILE:
            default = "<data>/agent_kill_switch"
        keys.append({
            "key": key,
            "kind": field.kind,
            "default": default,
            "min": _render(field.minimum),
            "max": _render(field.maximum),
            "choices": sorted(field.choices) if field.choices else None,
        })

    strict = []
    lenient = []
    for key, field in s._SPEC.items():
        if key == s.KEY_KILL_SWITCH_FILE:
            continue
        for raw in SAMPLES[field.kind]:
            try:
                stored = s._serialise(field, s._parse(key, field, raw, strict=True))
                strict.append({"key": key, "raw": raw, "stored": stored})
            except ValueError as exc:
                strict.append({"key": key, "raw": raw, "error": str(exc)})
        for text in STORED[field.kind]:
            value = s._parse(key, field, text, strict=False)
            lenient.append({"key": key, "stored": text, "reads": _render(value)})

    fixture = {
        "_comment": "Generated by scripts/agent/capture_settings.py from the web. Do not edit.",
        "keys": keys,
        "voice_keys": list(s.get_voice_defaults()),
        "websearch_keys": [
            s.KEY_WEBSEARCH_PROVIDER,
            s.KEY_WEBSEARCH_PERPLEXITY_MODEL,
            s.KEY_WEBSEARCH_MAX_CALLS_PER_TURN,
            s.KEY_WEBSEARCH_DAILY_CAP,
            s.KEY_WEBSEARCH_USAGE,
        ],
        "websearch_defaults": s.get_websearch_defaults(),
        "strict": strict,
        "lenient": lenient,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {OUT}: {len(keys)} keys, {len(strict)} strict and {len(lenient)} lenient cases")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "../openalgo"))
